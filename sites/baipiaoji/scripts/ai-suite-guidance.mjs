export function suiteGuidance(tool, lang) {
  if (!Object.hasOwn(guidance, tool.id)) return {};
  const {useCase, note, fieldHints, resultLabels, relatedIds} = guidance[tool.id];
  const localeIndex = lang === 'zh' ? 0 : 1;
  const localized = fields => Object.fromEntries(
    Object.entries(fields).map(([key, copies]) => [key, copies[localeIndex]]),
  );
  return {
    useCase: useCase[localeIndex],
    note: note[localeIndex],
    fieldHints: localized(fieldHints),
    resultLabels: localized(resultLabels),
    relatedIds,
  };
}
