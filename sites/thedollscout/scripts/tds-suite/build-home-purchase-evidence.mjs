import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';

const catalogue = new URL('../../content/amazon-products.json', import.meta.url);
const compiled = new URL('../../collector-assets/tds-suite/home-purchase-evidence.mjs', import.meta.url);
const count = 800;

function allocate(groups, total) {
  const all = groups.reduce((sum, group) => sum + group.length, 0);
  const quotas = groups.map((group, index) => {
    const numerator = total * group.length;
    return {index, count: Math.floor(numerator / all), remainder: numerator % all};
  });
  const left = total - quotas.reduce((sum, q) => sum + q.count, 0);
  const ranked = [...quotas].sort((a,b) => b.remainder - a.remainder || a.index - b.index);
  for (const quota of ranked.slice(0, left)) quota.count++;
  return quotas.flatMap(({index,count}) => groups[index].slice(0, count));
}

function validSource(url) {
  const source = new URL(url);
  return source.protocol === 'https:' && !source.username && !source.password && !source.port && !source.searchParams.has('tag');
}

function validRecord(row) {
  const required = ['id','name','brand','model','category','sourceUrl','checked','checkEn','checkDe','checkZh'];
  return required.every(key => typeof row[key] === 'string' && row[key].trim()) &&
    /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(row.id) && row.id.length <= 50 &&
    validSource(row.sourceUrl) && /^\d{4}-\d{2}-\d{2}$/.test(row.checked) &&
    (!row.deVariant || validSource(row.deVariant.sourceUrl));
}

export function buildEvidence({input = catalogue, output = compiled, check = false} = {}) {
  const data = JSON.parse(readFileSync(input, 'utf8'));
  if (!Array.isArray(data.products) || data.products.length < count) throw Error('At least 800 distinct catalogued models required');
  const groups = new Map();
  const seenIds = new Set(), seenModels = new Set();
  for (const row of data.products) {
    if (!validRecord(row)) throw Error(`Invalid model source record: ${row?.id}`);
    const modelKey = [row.brand, row.model].map(text => text.normalize('NFKC').toLowerCase().replace(/\s+/g,' ').trim()).join('|');
    if (seenIds.has(row.id) || seenModels.has(modelKey)) throw Error(`Duplicate model source record: ${row.id}`);
    seenIds.add(row.id);
    seenModels.add(modelKey);
    if (!groups.has(row.category)) groups.set(row.category, []);
    groups.get(row.category).push(row);
  }
  const selected = allocate([...groups.keys()].sort().map(key => groups.get(key)), count);
  const evidence = selected.map(row => [
    row.id,row.name,row.brand,row.model,row.category,row.sourceUrl,row.checked,row.checkEn,row.checkDe,row.checkZh,
    ...(row.deVariant ? [[row.deVariant.name,row.deVariant.model,row.deVariant.sourceUrl,row.deVariant.checked]] : []),
  ]);
  const text = '// Generated by scripts/tds-suite/build-home-purchase-evidence.mjs.\nexport const HOME_PURCHASE_EVIDENCE = [\n' +
    evidence.map(row => '  ' + JSON.stringify(row)).join(',\n') + '\n];\n';
  if (check && readFileSync(output,'utf8') !== text) throw Error('The model-tool evidence snapshot is stale. Regenerate it from the catalogue.');
  if (!check) writeFileSync(output,text);
  return {file:fileURLToPath(output),count:evidence.length};
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = buildEvidence({check:process.argv.includes('--check')});
  console.log(`${result.count} exact-model evidence records: ${result.file}`);
}
