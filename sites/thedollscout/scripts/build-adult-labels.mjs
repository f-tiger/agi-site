/* Applies the adult-content labelling decided in scripts/adult-labels.mjs:
   the per-page <meta name="rating"> tag, and the Rating: header block in
   _headers.

   Generated rather than hand-maintained. A 40-line list kept by hand drifts —
   this repository has lost data to exactly that failure more than once — and a
   label that drifts is worse than one that is simply wrong, because nobody can
   tell which pages are currently declared adult without reading all of them.

   The 18+ age gate is not touched by any of this. It is injected by js/main.js
   on every page regardless of which list the page is in.

   Run: node scripts/build-adult-labels.mjs */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { ADULT_SURFACES, NON_EXPLICIT, RTA_LABEL, adultPaths } from "./adult-labels.mjs";

const META = '<meta name="rating" content="adult">';
let changed = 0;
let problems = 0;

/* ---- 1. the per-page meta tag ---- */
for (const page of ADULT_SURFACES) {
  if (!existsSync(page)) {
    console.log(`FAIL  ${page} is listed as an adult surface but does not exist.`);
    problems++;
    continue;
  }
  const html = readFileSync(page, "utf8");
  if (html.includes(META)) continue;
  /* Insert after the canonical link if there is one, else after <title>, so
     the tag lands in <head> rather than wherever a regex happened to match. */
  const anchor = /<link rel="canonical"[^>]*>/.exec(html) || /<\/title>/.exec(html);
  if (!anchor) {
    console.log(`FAIL  ${page}: no <link rel="canonical"> or </title> to anchor the rating tag to.`);
    problems++;
    continue;
  }
  const at = anchor.index + anchor[0].length;
  writeFileSync(page, html.slice(0, at) + "\n" + META + html.slice(at));
  console.log(`  +meta ${page}`);
  changed++;
}

for (const { page } of NON_EXPLICIT) {
  if (!existsSync(page)) {
    console.log(`FAIL  ${page} is listed as non-explicit but does not exist.`);
    problems++;
    continue;
  }
  const html = readFileSync(page, "utf8");
  if (!html.includes(META)) continue;
  /* Remove the tag and the newline it sits on, so repeated runs cannot leave a
     growing stack of blank lines in <head>. */
  writeFileSync(page, html.replace(new RegExp(`\\n?${META.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`), ""));
  console.log(`  -meta ${page}`);
  changed++;
}

/* ---- 2. the Rating: header ----
   It used to sit under `/*`, which put an adult label on the sitemap, the
   dataset, llms.txt and the MCP endpoint. _headers has no negation, so the
   adult paths are enumerated. The security headers stay on `/*` — narrowing
   THOSE would be a real regression, so they are rebuilt verbatim. */
const SECURITY = [
  "X-Content-Type-Options: nosniff",
  "X-Frame-Options: DENY",
  "Referrer-Policy: strict-origin-when-cross-origin",
  "Permissions-Policy: geolocation=(), microphone=(), camera=()",
];

const headers =
  `# Generated by scripts/build-adult-labels.mjs — do not edit by hand.\n` +
  `# Security headers apply everywhere. The adult Rating: label applies only to\n` +
  `# pages that show or recommend the product; see scripts/adult-labels.mjs for\n` +
  `# the reasoning, and note the 18+ age gate is separate and site-wide.\n` +
  `/*\n` + SECURITY.map((h) => `  ${h}`).join("\n") + "\n\n" +
  adultPaths().map((p) => `${p}\n  Rating: ${RTA_LABEL}`).join("\n") + "\n";

if (!existsSync("_headers") || readFileSync("_headers", "utf8") !== headers) {
  writeFileSync("_headers", headers);
  console.log(`  rewrote _headers — Rating: on ${adultPaths().length} path(s), security headers still on /*`);
  changed++;
}

console.log(
  problems
    ? `\n${problems} problem(s). Fix scripts/adult-labels.mjs before deploying.`
    : `\n${changed || "No"} change(s). ${ADULT_SURFACES.length} adult surfaces, ${NON_EXPLICIT.length} non-explicit pages.`
);
process.exit(problems ? 1 : 0);
